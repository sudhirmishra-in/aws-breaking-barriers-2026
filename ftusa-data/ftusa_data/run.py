"""Run the whole data pipeline.

    python -m ftusa_data.run --raw <folder with FTUSA files> --out out
    # optional AWS layers (need boto3 + credentials):
    python -m ftusa_data.run --raw ... --out out --bedrock-model-id <claude model id> --comprehend --aws-region us-east-1

Writes
  out/tables/<table>/<table>.csv      producers, certifications, regions, premium_projects,
                                      survey_summary, survey_choice_shares
  out/standards/standard_clauses.jsonl, standard_objectives.csv
  out/review/tag_labeling_sample.csv  fill human_tags, then: python -m ftusa_data.run --evaluate-tags <csv>
  out/review/scenario_candidates.csv  real producers with the richest data for demo scenarios
  out/review/scope_test_pairs.csv     (session producer, other producer) pairs for negative scope tests
  out/report.json                     counts + warnings
  out/DATA_DICTIONARY.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from . import io, pii, producers, projects, standards, surveys, tagging
from .config import MIN_N, PRIORITY_COUNTRIES, PRIORITY_CROPS


def scenario_candidates(prod: pd.DataFrame, proj: pd.DataFrame, summ: pd.DataFrame) -> pd.DataFrame:
    p = prod[prod.is_priority & (prod.n_projects > 0)].copy()
    tags = proj.groupby("account_sk").primary_tag.agg(lambda s: "|".join(sorted(s.dropna().unique())))
    p["project_tags"] = p.account_sk.map(tags)
    p["n_distinct_tags"] = p.project_tags.fillna("").map(lambda s: len([x for x in s.split("|") if x]))
    latest = summ.sort_values("survey_year").groupby("account_sk").tail(1).set_index("account_sk")
    p["latest_survey_year"] = p.account_sk.map(latest.survey_year)
    p["survey_highlight"] = p.account_sk.map(
        lambda a: (f"{latest.at[a, 'pct_harvest_decreased']}% harvest decreased (n={latest.at[a, 'n_harvest_decreased']}); "
                   f"top reasons: {latest.at[a, 'top_harvest_change_reasons']}") if a in latest.index else None)
    peers = proj[proj.is_peer_eligible].merge(prod[["account_sk", "primary_crop"]], on="account_sk")
    p["n_peer_projects_same_crop"] = [int(((peers.primary_crop == c) & (peers.account_sk != a)).sum())
                                      for a, c in zip(p.account_sk, p.primary_crop)]
    p["score"] = p.n_projects + 3 * p.has_survey.astype(int) + p.n_distinct_tags
    cols = ["account_sk", "display_id", "org_name_fictional", "country", "region", "entity_type", "primary_crop",
            "certification_status", "n_projects", "project_tags", "has_survey", "latest_survey_year",
            "survey_highlight", "n_peer_projects_same_crop", "score"]
    return p.sort_values("score", ascending=False)[cols]


def scope_pairs(prod: pd.DataFrame) -> pd.DataFrame:
    """Hardest leakage cases: another producer with the same crop, same region (else same country)."""
    rows = []
    pri = prod[prod.is_priority]
    for r in pri.itertuples():
        same = prod[(prod.account_sk != r.account_sk) & (prod.primary_crop == r.primary_crop)]
        cand = same[same.region_id == r.region_id]
        why = "same crop + region"
        if cand.empty:
            cand, why = same[same.country == r.country], "same crop + country"
        if cand.empty:
            continue
        o = cand.sort_values("n_projects", ascending=False).iloc[0]
        rows.append({"session_account_sk": r.account_sk, "session_display_id": r.display_id,
                     "other_account_sk": o.account_sk, "other_display_id": o.display_id, "why_hard": why})
    return pd.DataFrame(rows)


def data_dictionary(out: Path, tables: dict[str, pd.DataFrame], docs: dict[str, dict]):
    lines = ["# Data dictionary", "", "Generated by `python -m ftusa_data.run`. Primary key everywhere: `account_sk`.", ""]
    for name, df in tables.items():
        d = docs.get(name, {})
        lines += [f"## {name}  ({len(df)} rows)", "", "| column | description |", "|---|---|"]
        for c in df.columns:
            desc = d.get(c)
            if desc is None and c.startswith("n_"):
                desc = d.get("n_<metric>", "count")
            if desc is None and c.startswith("top_"):
                desc = d.get("top_<question>", "")
            lines.append(f"| `{c}` | {desc or ''} |")
        lines.append("")
    lines += ["## standard_clauses.jsonl", "", "| field | description |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in standards.DOCS.items()]
    (out / "DATA_DICTIONARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", help="folder containing the FTUSA files")
    ap.add_argument("--out", default="out")
    ap.add_argument("--bedrock-model-id", help="enable LLM tagging layer (Claude model ID or inference profile)")
    ap.add_argument("--llm-all", action="store_true", help="LLM re-tags every project, not just weak ones")
    ap.add_argument("--comprehend", action="store_true", help="add Amazon Comprehend PII detection")
    ap.add_argument("--aws-region")
    ap.add_argument("--evaluate-tags", metavar="CSV", help="score a filled-in tag_labeling_sample.csv and exit")
    a = ap.parse_args(argv)

    if a.evaluate_tags:
        print(json.dumps(tagging.evaluate(Path(a.evaluate_tags)), indent=2))
        return
    if not a.raw:
        ap.error("--raw is required")
    raw, out = Path(a.raw), Path(a.out)
    report = {"warnings": []}

    print("1/5 projects")
    accounts = io.read_csv(raw, "accounts")
    acct_country = dict(zip(accounts.account_sk, accounts.country_name.map(io.norm_country)))
    proj = projects.build(io.read_csv(raw, "projects_full"), io.read_csv(raw, "projects_env"), acct_country)
    proj = tagging.apply(proj, a.bedrock_model_id, a.llm_all, out / "cache", a.aws_region)
    proj = pii.apply(proj, a.comprehend, a.aws_region)
    proj = projects.finalize(proj)

    print("2/5 surveys")
    summ, shares, sstats = surveys.build(io.read_csv(raw, "survey_single"), io.read_csv(raw, "survey_multi"),
                                         io.read_csv(raw, "survey_header"), io.read_csv(raw, "household_header"),
                                         set(accounts.account_sk))
    report["surveys"] = sstats

    print("3/5 producers, certifications, regions")
    prod, certs, w = producers.build(accounts, proj, set(summ.account_sk))
    report["warnings"] += w
    regions = producers.regions_from_projects(proj)

    print("4/5 standards")
    sst = standards.build(io.find(raw, "aps_xlsx"), io.find(raw, "fps_xlsx"), out / "standards")
    report["warnings"] += sst.pop("warnings")
    report["standards"] = sst

    print("5/5 write")
    tables = {"producers": prod, "certifications": certs, "regions": regions, "premium_projects": proj,
              "survey_summary": summ, "survey_choice_shares": shares}
    for n, df in tables.items():
        io.write(df, out, n)
    rv = out / "review"
    rv.mkdir(parents=True, exist_ok=True)
    tagging.labeling_sample(proj).to_csv(rv / "tag_labeling_sample.csv", index=False)
    scenario_candidates(prod, proj, summ).to_csv(rv / "scenario_candidates.csv", index=False)
    scope_pairs(prod).to_csv(rv / "scope_test_pairs.csv", index=False)
    data_dictionary(out, tables, {"producers": producers.DOCS["producers"], "certifications": producers.DOCS["certifications"],
                                  "regions": producers.DOCS["regions"], "premium_projects": projects.DOCS,
                                  "survey_summary": surveys.DOCS_SUMMARY, "survey_choice_shares": surveys.DOCS_SHARES})

    pri = prod[prod.is_priority]
    report.update({
        "rows": {n: len(df) for n, df in tables.items()},
        "producers": {"total": len(prod), "priority": len(pri),
                      "priority_by_country_crop": {f"{k[0]} / {k[1]}": int(v) for k, v in
                                                   pri.groupby(["country", "primary_crop"]).size().items()},
                      "entity_types": prod.entity_type.value_counts().to_dict(),
                      "with_survey": int(prod.has_survey.sum())},
        "projects": {"tag_source": proj.tag_source.value_counts().to_dict(),
                     "primary_tag": proj.primary_tag.value_counts(dropna=False).rename(index=str).to_dict(),
                     "pending_confirmation": int(proj.tag_pending_confirmation.sum()),
                     "peer_eligible": int(proj.is_peer_eligible.sum()), "pii_flagged": int(proj.pii_flag.sum()),
                     "test_records": int(proj.is_test_record.sum()),
                     "merge_ambiguous": int(proj.merge_ambiguous.sum()), "country_mismatch": int(proj.country_mismatch.sum())},
        "regions_with_centroid": int(regions.latitude.notna().sum()),
        "config": {"priority_countries": PRIORITY_COUNTRIES, "priority_crops": PRIORITY_CROPS, "min_n": MIN_N,
                   "llm_tagging": bool(a.bedrock_model_id), "comprehend": a.comprehend},
    })
    (out / "report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    print(json.dumps({k: report[k] for k in ("rows", "producers", "projects")}, indent=1, ensure_ascii=False, default=str))
    print(f"{len(report['warnings'])} warnings -> {out / 'report.json'}")


if __name__ == "__main__":
    main()
